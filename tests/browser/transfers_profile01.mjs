let signatureSequence = 0
async function signing(body) {
  for (const task of body.signing_tasks || []) {
    const endpoint = task.signing_endpoint.replace(/^\/api/, '')
    const summary = await api(endpoint)
    const image = await page.evaluate(sequence => { const canvas = document.createElement('canvas'); canvas.width = 320; canvas.height = 120; const ctx = canvas.getContext('2d'); ctx.fillStyle = '#fff'; ctx.fillRect(0, 0, 320, 120); ctx.fillStyle = `rgb(${sequence},50,90)`; ctx.fillRect(5, 5, 2, 2); ctx.strokeStyle = '#123'; ctx.beginPath(); ctx.moveTo(20, 40); ctx.lineTo(120, 60); ctx.stroke(); return canvas.toDataURL('image/png').split(',')[1] }, ++signatureSequence)
    await api(endpoint, { consent_accepted: true, consent_text: summary.consent_notice,
      strokes: [Array.from({ length: 8 }, (_, i) => ({ x: 20 + i * 12, y: 40 + i, t: i * 10 }))],
      image_base64: image, canvas_width: 320, canvas_height: 120 })
    await api(endpoint + '/confirm', {})
  }
}
