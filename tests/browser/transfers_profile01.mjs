async function api(path, data, method = 'POST') {
  const csrf = (await context.cookies()).find(cookie => cookie.name === 'assetcore_csrf')?.value
  const response = await page.request.fetch(base + '/api' + path, { timeout: 180000, method: data === undefined ? 'GET' : method,
    ...(data === undefined ? {} : { data }), headers: { 'X-CSRF-Token': csrf || '' } })
  if (!response.ok()) {
    const code = (await response.json().catch(() => ({}))).detail?.code || 'unknown'
    throw new Error(`QA API status ${response.status()} (${/^[a-z0-9_]+$/.test(code) ? code : 'unknown'})`)
  }
  if (response.status() === 204) return null
  return response.json()
}
async function shot(name, width = 1440) {
  await page.setViewportSize({ width, height: 1000 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  const dialogs = page.getByRole('dialog')
  if (await dialogs.count()) await expect.poll(() => dialogs.last().evaluate(dialog => {
    const rect = dialog.getBoundingClientRect()
    return rect.left >= 0 && rect.right <= innerWidth && rect.top >= 0 && rect.bottom <= innerHeight + 1 && dialog.scrollWidth <= dialog.clientWidth + 1
  })).toBe(true)
  await page.screenshot({ path: `${out}/${name}-${width}.png`, fullPage: true })
}
